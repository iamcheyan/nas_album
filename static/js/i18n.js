function setMapProvider(providerId) {
    if (!MAP_PROVIDERS[providerId]) return false;
    localStorage.setItem('nas-album-map-provider', providerId);
    // If map exists, switch tile layer immediately
    if (typeof mapInstance !== 'undefined' && mapInstance && currentTileLayer) {
        mapInstance.removeLayer(currentTileLayer);
        const layer = MAP_PROVIDERS[providerId];
        currentTileLayer = L.tileLayer(layer.url, {
            attribution: layer.attribution,
            subdomains: layer.subdomains,
            maxZoom: layer.maxZoom
        }).addTo(mapInstance);
    }
    return true;
}

function t(key, ...args) {
    const str = I18N[currentLang]?.[key] || I18N['en']?.[key] || key;
    return args.reduce((s, arg, i) => s.replace(new RegExp(`\\{${i}\\}`, 'g'), arg), str);
}

function setLang(lang) {
    if (!I18N[lang]) return;
    currentLang = lang;
    localStorage.setItem('nas-album-lang', lang);
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : lang;

    // Update all data-i18n elements
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.dataset.i18n;
        if (key) el.textContent = t(key);
    });

    // Update placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.dataset.i18nPlaceholder;
        if (key) el.placeholder = t(key);
    });

    // Update language selector buttons
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.toggle('active', btn.dataset.lang === lang);
    });

    // Update title attributes with data-i18n-title
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.dataset.i18nTitle;
        if (key) el.title = t(key);
    });

    // Update aria-label with data-i18n-aria-label
    document.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
        const key = el.dataset.i18nAriaLabel;
        if (key) el.setAttribute('aria-label', t(key));
    });

    // Switch map tile layer if map exists (use user's provider preference, not language default)
    if (typeof mapInstance !== 'undefined' && mapInstance && currentTileLayer) {
        mapInstance.removeLayer(currentTileLayer);
        const providerId = getMapProvider();
        const layer = MAP_PROVIDERS[providerId] || MAP_PROVIDERS['osm'];
        currentTileLayer = L.tileLayer(layer.url, {
            attribution: layer.attribution,
            subdomains: layer.subdomains,
            maxZoom: layer.maxZoom
        }).addTo(mapInstance);
    }

    // Dispatch event for app.js to refresh dynamic content
    window.dispatchEvent(new CustomEvent('languagechanged', { detail: { lang } }));
}

function initI18n() {
    document.documentElement.lang = currentLang === 'zh' ? 'zh-CN' : currentLang;
    setLang(currentLang);
}

